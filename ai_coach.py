import json

from gemini_service import ask_gemini

MIN_DAYS = 3

PROMPT = """คุณเป็นโค้ชโภชนาการ วิเคราะห์ข้อมูลสรุปของผู้ใช้ด้านล่าง ตอบเป็นภาษาไทย กระชับ อ่านง่าย

กติกา:
- ใช้เฉพาะตัวเลขที่อยู่ในข้อมูลเท่านั้น ห้ามแต่งหรือเดาตัวเลขเพิ่ม
- ถ้าข้อมูลบางอย่างไม่มี (เช่น ไม่มีข้อมูลน้ำหนัก) ให้บอกว่าไม่มีข้อมูล ไม่ต้องวิเคราะห์ส่วนนั้น
- ไม่วินิจฉัยโรค ไม่แนะนำยา และถ้าพบสิ่งที่น่ากังวลให้แนะนำให้ปรึกษาแพทย์หรือนักกำหนดอาหาร
- days_logged คือจำนวนวันที่ผู้ใช้บันทึกจริง จาก period_days วัน ให้พิจารณาความน่าเชื่อถือของข้อมูลด้วย

ตอบตามหัวข้อนี้:
### 📌 ภาพรวม
(2-3 ประโยค เทียบค่าเฉลี่ยกับเป้า)
### 🔍 ข้อสังเกต
(3-4 ข้อ อ้างอิงตัวเลข)
### 🛠️ สิ่งที่ควรปรับ
(2-3 ข้อ ทำได้จริงในชีวิตประจำวัน)
### 🗓️ แผนสัปดาห์หน้า
(เป้าหมายเล็กๆ 2-3 ข้อ)

ข้อมูลสรุป (JSON):
{data}
"""


def analyze_week(summary: dict) -> str:
    if summary.get("days_logged", 0) < MIN_DAYS:
        return (
            f"ℹ️ ข้อมูลยังน้อยเกินไป (บันทึกแล้ว {summary.get('days_logged', 0)} วัน) "
            f"ลองบันทึกอย่างน้อย {MIN_DAYS} วัน แล้วค่อยให้ AI วิเคราะห์ จะแม่นยำกว่า"
        )
    prompt = PROMPT.format(data=json.dumps(summary, ensure_ascii=False, indent=2))
    return ask_gemini(prompt)
